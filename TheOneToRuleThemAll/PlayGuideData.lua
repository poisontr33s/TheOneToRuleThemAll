THE ONE TO RULE THEM ALL — SPILLEKORT
25. oktober 2026

SUBBURST: SEKS OFFENSIVE KNAPPER

Standard /tor subburst:
1 Builder · 2 Shuriken Storm · 3 Eviscerate/Coup · 4 Black Powder/Coup
5 Secret Technique · 6 Dance + Blades + Goremaw
7 Kick · 8 Feint · 9 Vanish

Compact /tor subburst compact:
1 Builder / Alt+1 Storm · 2 Eviscerate/Coup / Alt+2 Black Powder/Coup
3 Secret Technique · 4 Dance + Blades + Goremaw
5 Cloak · 6 Vial · 7 Kick · 8 Feint · 9 Vanish

Compact har fire offensive talltaster pluss Alt, men de samme seks valgene.
On-use-trinket, andre items og utility kommer i tillegg. Bruk plasseringen
som passer hendene dine; compact har ingen egen simulert skadegevinst.

BEGYNN HER

Bruk talentkoden i TALENTS.txt. Det er din opprinnelige Trickster/Danse-kode,
ikke Potent Powder. Oppsettet endrer hvordan evnene betjenes og prioriteres.

Åpne fra Stealth og få Slice and Dice i gang med Eviscerate. Med Slice aktiv:
bruk burst-makroen når Goremaw er klar, også hvis det ikke passer med neste
planlagte Dance. Er du allerede i Dance, bruker du samme makro for Goremaw.
Det er derfor en separat Goremaw-knapp kan fjernes.

Makroen forsøker Dance, så Blades, så Goremaw. Den velger ikke tidspunktet.
Secret Technique står fortsatt separat. Kjør finishere ved 6+ combo points.
Mangler Slice, bruk Eviscerate først. Ellers har Coup prioritet over vanlig
finisher; Eviscerate brukes på 1–2 mål og Black Powder på 3+.

NÅR DU VIL FØLGE DEN MEST SKADESTERKE TESTEDE PRIORITETEN

• Vanlig builder: Shadowstrike i Stealth/Dance, Backstab ellers på ett mål;
  Storm på to eller flere. Unntaket er første builder mens Premeditation er
  aktiv i Dance: da bruker modellen Storm også på ett mål. Det betyr ikke
  at du skal bruke en builder først dersom du allerede har nok CP til finisher.
• Uten Stealth/Dance venter modellen med builder til over 60 energy. Inne i
  vinduet bygger den når det trengs. Den har ingen ekstra finisher-pooling
  eller bevisste builders ved fulle CP for å optimalisere Ancient Arts.
• Ved 6+ CP brukes Secret i Dance. Den brukes også utenfor Dance hvis Dance
  er utilgjengelig og Secrets gjeldende cooldown-varighet er under 18 sekunder.
• Ingen offensive Vanish eller aktive racials inngår i denne prioriteten.

BURST-TIMINGEN SOM FORTSATT ER MED I SIMULERINGEN

1. Goremaw klar + Slice aktiv: trykk burst, uavhengig av CP.
2. Blades klar: gå normalt inn i Dance med 6+ CP, minst 30 energy og Slice
   aktiv. Makroen legger Blades umiddelbart etter Dance.
3. Secret klar: gå normalt inn i Dance med samme forberedelse. Modellen kan
   holde igjen for Blades: gjenværende Blades-cooldown må være minst
   25 sekunder minus Secrets gjeldende cooldown-varighet.
4. Mens Blades er aktiv: bruk en ny Dance når den forrige er over og en
   charge er tilgjengelig. Denne ekstra Dance krever ikke 6 CP.
5. Modellen bruker også sluttfase-regler ved omtrent 10–20 sekunder igjen
   av fighten eller målets liv. Dette kan du bare anslå i en faktisk dungeon.

Dette er sim-forutsetninger, ikke en skjult funksjon i addon-en. Separate
Dance/Blades ligger på bar 2 og kan brukes til å følge cooldowns. Ikke bruk
burst-makroen som en knapp du spammer gjennom hele rotasjonen.

ENKLERE BUILDER-/FINISHER-VALG, MED MÅLT KOSTNAD

Samme oppsett kan brukes med denne testede forenklingen:
• Builder på ett mål; Storm på 2+. Ingen Storm-unntak på ett mål.
• Ved 6+ CP: vedlikehold Slice; deretter Secret når klar; ellers Coup og
  vanlig finisher. Ingen Dance-betingelse på Secret.
• Bygg når du trenger CP og har energy nok, uten bevisst 60-energy-venting.

Denne varianten ga omtrent 1,25 % mindre blandet skade og 3,32 % mindre
boss-skade enn den presise seks-knapperskandidaten. Den beholder fortsatt
burst-reglene over. Den fullstendig enkle burst-planen vi også prøvde mistet
mer skade og ble ikke valgt. Tallene fra den presise modellen kan derfor
ikke leses som hva en vilkårlig enkel rotasjon automatisk vil levere.

ASSASSINATION: NÅR ROLIGERE TEMPO BETYR MEST

/tor assa har åtte offensive evner. /tor assa compact samler dem på seks
talltaster pluss Alt:
1 Mutilate / Alt+1 Fan · 2 Envenom / Alt+2 Crimson Tempest
3 Garrote · 4 Rupture · 5 Kingsbane · 6 Deathmark
7 Kick · 8 Feint · 9 Vanish

Hold Garrote og Rupture på et mål som lever lenge nok. Bruk 5+ CP på Rupture.
Crimson Tempest er en generator som sprer bleeds; Envenom er spender også
på AoE. Bygg med Mutilate på ett mål og Fan på flere. Når bleeds er ivaretatt,
bruk Envenom ved 5+ CP uten avansert pooling.

Ha bleeds og Envenom-buffen oppe til burst. Deathmark og Kingsbane brukes
sammen når de er klare; Kingsbane brukes også mellom Deathmark-vinduene.
Tea brukes automatisk gjennom talentet; Vanish er verktøy, ikke rutine-DPS.
Den detaljerte cooldown-prioriteten ligger i SimC-filene, ikke i addon-en.

På den nye malen var Assa omtrent 43 logiske handlinger/minutt i den blandede
testen, mot Subs 55, men med omtrent 13 % lavere skade. Dette er et målt
alternativ for roligere tempo. Handlinger/minutt er ikke fysisk tastespam.

FELLES

Kick, defensives og bevegelse brukes etter mekanikkene. Flytt deg ut av
farlige felt selv når burst er oppe. Disse simuleringene kan ikke måle
hvor mye bedre du personlig spiller med et enklere oppsett.

De gamle sub/sublite-layoutene er beholdt som alternativer. Sublite dropper
Goremaw helt, mens subburst beholder evnen på en delt knapp. De er ikke samme
seks-knappersprioritet. Resultater fra gammel gear-mal er ikke nye resultater.
