    test("play guide preserves complete source priorities including burst rules and measured tradeoffs",function()
        local path=debug.getinfo(1,"S").source:gsub("^@","")
        local file=assert(io.open((path:match("^(.*)[/\\]") or ".").."/../PLAY-GUIDE.txt","rb"))
        local source=file:read("*a"); file:close()
        local function section(first,last)
            local start=assert(source:find(first,1,true))
            local stop=assert(source:find(last,start+#first,true))
            return source:sub(start,stop-1):match("^%s*(.-)%s*$")
        end
        local common=section("FELLES\n","De gamle sub/sublite-layoutene")
        local sub=section("BEGYNN HER\n","ASSASSINATION:")
        local assa=section("ASSASSINATION:","FELLES\n")
        local A=c.addon()
        expect(A.playGuideSource==source,"Embedded guide differs from PLAY-GUIDE.txt; run tools/sync_play_guide.py")
        expect(A.GetPlayGuide("subburst"):find(sub,1,true),"SubBurst guide changed or omitted source text")
        expect(A.GetPlayGuide("subburst"):find(common,1,true),"SubBurst guide omitted shared guidance")
        expect(A.GetPlayGuide("assa"):find(assa,1,true),"Assassination guide changed or omitted source text")
        expect(A.GetPlayGuide("assa"):find(common,1,true),"Assassination guide omitted shared guidance")
        for _,id in ipairs({"sub","sublite","blood-sanlayn","blood-deathbringer","unknown"}) do
            expect(A.GetPlayGuide(id)==nil,"Another profile inherited an unsupported priority")
        end
    end)
