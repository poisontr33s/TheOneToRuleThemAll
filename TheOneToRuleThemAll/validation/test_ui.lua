-- Real panel callbacks with widget mocks; rendering is tested in WoW.
return function(c)
    local test, expect, copy, equal = c.test,c.expect,c.copy,c.equal
    local function open() c.addon().TogglePanel(); return c.addon().panel end
    test("Opening the lazy panel preserves bars and saved data",function()
        local S=c.state(); expect(not c.addon().panel and #S.frames==1)
        S.slots[1]={kind="item",id=777}; local before=copy(S.slots); local p=open()
        expect(p.selectedId=="standard-subtlety" and p.applyButton:IsEnabled())
        expect(not p.mouseoverButton:IsShown() and p.compactButton==nil)
        expect(equal(before,S.slots) and S.created==0 and S.placements==0 and not TheOneToRuleThemAllDB)
    end)
    test("Apply and Undo buttons use guarded commands",function()
        local S=c.state(); S.slots[1]={kind="item",id=777}; local before=copy(S.slots)
        local p=open(); p.applyButton:Click()
        expect(p.undoButton:IsEnabled() and not p.applyButton:IsEnabled())
        p.undoButton:Click()
        expect(equal(before,S.slots) and p.applyButton:IsEnabled() and not p.undoButton:IsEnabled())
    end)
    test("A stale Apply callback cannot bypass combat or a changed spec",function()
        local S=c.state(); local p=open(); local click=p.applyButton:GetScript("OnClick")
        S.combat=true; click(p.applyButton)
        expect(S.placements==0 and not p.applyButton:IsEnabled())
        S.combat=false; p:Refresh(); S.spec=259; click(p.applyButton)
        expect(S.placements==0 and not TheOneToRuleThemAllDB)
    end)
    test("Binding refresh shows current keys without applying",function()
        local S=c.state(); local p=open()
        S.bindingKeys.ACTIONBUTTON1={"SHIFT-Q"}; S.dispatchUIEvent("UPDATE_BINDINGS")
        expect(p.previewText:GetText():find("Shift+Q",1,true))
        expect(S.placements==0 and S.bindingCalls==0)
    end)
    test("Healer Mouseover selection stays read-only",function()
        local S=c.state(); S.class="PRIEST"; S.spec=257; local p=open()
        expect(p.layout=="standard" and p.mouseoverButton:IsShown())
        p.mouseoverButton:Click(); expect(p.layout=="mouseover" and #p.snapshot.plan.macros>0)
        p.standardButton:Click(); expect(p.layout=="standard" and #p.snapshot.plan.macros==0)
        expect(S.placements==0 and S.created==0 and not TheOneToRuleThemAllDB)
    end)
    test("Incomplete Undo offers retry until the original item returns",function()
        local S=c.state(); S.slots[1]={kind="item",id=777}; local p=open()
        p.applyButton:Click(); S.gone[777]=true; p.undoButton:Click()
        expect(TheOneToRuleThemAllDB.backup.state=="needs-undo" and p.undoButton:IsEnabled())
        expect(p.statusText:GetText():find("Undo incomplete",1,true))
        S.gone[777]=nil; p.undoButton:Click()
        expect(S.slots[1].id==777 and not p.undoButton:IsEnabled())
    end)
    test("Occupied cursor and unknown specs remain passive",function()
        local S=c.state(); S.cursor={kind="item",id=777}; local p=open()
        expect(not p.applyButton:IsEnabled() and S.cursor.id==777)
        S.cursor=nil; S.spec=999999; S.dispatchUIEvent("PLAYER_SPECIALIZATION_CHANGED","player")
        expect(not p.applyButton:IsEnabled() and not p.talentsButton:IsEnabled())
        expect(S.placements==0 and S.created==0)
    end)
    test("Closing removes refresh events; reopening reuses the panel",function()
        local p=open(); local frames=#c.state().frames
        p.closeButton:Click(); expect(not p:IsShown() and next(p.events)==nil)
        expect(open()==p and #c.state().frames==frames and c.state().placements==0)
    end)
    test("Gear details follow the specialization when a Paladin changes role",function()
        local S=c.state(); S.class="PALADIN"; S.spec=65
        local p=open(); p.detailsButton:Click()
        expect(p.previewText:GetText():find("Sunfire Silk Spellthread",1,true))
        expect(p.previewText:GetText():find("Shaladrassil's Roots",1,true))
        S.spec=70; S.dispatchUIEvent("PLAYER_SPECIALIZATION_CHANGED","player")
        p.detailsButton:Click()
        expect(p.previewText:GetText():find("Forest Hunter's Armor Kit — Strength",1,true))
        expect(not p.previewText:GetText():find("Sunfire Silk Spellthread",1,true))
        expect(S.placements==0 and S.created==0)
    end)
end
